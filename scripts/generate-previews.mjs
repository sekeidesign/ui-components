// Writes content/previews.generated.ts — a module-scope map of every
// content/<slug>/Preview.tsx.
//
// Why generate instead of `dynamic(() => import(`../../content/${slug}/Preview`))`:
// calling dynamic() during render creates a fresh React.lazy on the fly, and a
// lazy component that suspends during hydration unwinds to the nearest
// Suspense boundary — the whole route — blanking the page with no error. Lazy
// components have to exist at module scope, which rules out a runtime slug
// lookup. Static import paths also keep both bundlers honest.
import { readdirSync, existsSync, writeFileSync, readFileSync } from "node:fs";
import path from "node:path";

const CONTENT_ROOT = path.join(process.cwd(), "content");
const OUT = path.join(CONTENT_ROOT, "previews.generated.ts");

const slugs = existsSync(CONTENT_ROOT)
	? readdirSync(CONTENT_ROOT, { withFileTypes: true })
			.filter((d) => d.isDirectory())
			.map((d) => d.name)
			.filter((slug) => existsSync(path.join(CONTENT_ROOT, slug, "Preview.tsx")))
			.sort()
	: [];

const body = `// GENERATED by scripts/generate-previews.mjs — do not edit.
// Regenerated on every \`pnpm dev\` and \`pnpm build\`.
import dynamic from "next/dynamic";
import type { ComponentType } from "react";

export const previews: Record<string, ComponentType> = {
${slugs.map((slug) => `\t"${slug}": dynamic(() => import("./${slug}/Preview")),`).join("\n")}
};
`;

// Avoid rewriting an identical file, which would churn the dev server.
if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== body) {
	writeFileSync(OUT, body);
	console.log(`previews.generated.ts: ${slugs.length} preview(s)`);
}
